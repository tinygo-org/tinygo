// Enable enables a CPU interrupt. The caller must first map the peripheral to
// a CPU interrupt line using the interrupt matrix.
func (i Interrupt) Enable() error {
	if i.num < firstCPUInt || i.num > lastCPUInt {
		return errors.New("interrupt number out of range")
	}

	// The enable registers are per core and peripherals are routed to core 0,
	// so the other cores ask core 0 to enable the line.
	switch currentCPU() {
	case 0:
		enableLine(i.num)
	default:
		enableOnCore0(uint32(i.num))
	}
	return nil
}

