// libPicolibc is a C library for bare metal embedded devices. It was originally
// based on newlib.
var libPicolibc = Library{
	name: "picolibc",
	makeHeaders: func(target, includeDir string) error {
		f, err := os.Create(filepath.Join(includeDir, "picolibc.h"))
		if err != nil {
			return err
		}
		return f.Close()
	},
	cflags: func(target, headerPath string) []string {
		root := goenv.Get("TINYGOROOT")
		picolibcDir := filepath.Join(root, "lib/picolibc")
		flags := []string{
			"-Werror",
			"-Wall",
			"-std=gnu11",
			"-D__TINY_STDIO",
			"-D_XOPEN_SOURCE=700",
			"-D__IO_DEFAULT='i'", // use __i_vfprintf and __i_vfscanf by default
			"-D__IEEE_LIBM",
			"-D__OBSOLETE_MATH_FLOAT=1", // use old math code that doesn't expect a FPU
			"-D__OBSOLETE_MATH_DOUBLE=0",
			"-D__IO_C99_FORMATS",
			"-D__PICOLIBC_ERRNO_FUNCTION=__errno_location",
			"-nostdlibinc",
			"-isystem", picolibcDir + "/libc/include",
			"-I" + picolibcDir + "/libc/stdio",
			"-I" + picolibcDir + "/libc/locale",
			"-I" + picolibcDir + "/libm/common",
			"-I" + headerPath,
		}
		if compileopts.CanonicalArchName(target) == "xtensa" {
			flags = append(flags,
				"-I"+filepath.Join(root, "lib/xtensa/include"),
				"-I"+picolibcDir+"/libc/machine/xtensa",
				"-D_XTENSA_HAVE_CONFIG_CORE_ISA_H",
			)
		}
		return flags
	},
	sourceDir: func() string { return filepath.Join(goenv.Get("TINYGOROOT"), "lib/picolibc") },
	librarySources: func(target string, _ bool) ([]string, error) {
		sources := append([]string(nil), picolibcSources...)
		if compileopts.CanonicalArchName(target) == "xtensa" {
			sources = append(sources, "libc/machine/xtensa/setjmp.S")
		}
		return sources, nil
	},
}

