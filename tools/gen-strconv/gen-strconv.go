// gen-strconv copies internal/strconv from GOROOT into a single file, with
// the table driven fast paths and any code only they used left out.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/importer"
	"go/parser"
	"go/printer"
	"go/token"
	"go/types"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// goVersion is compileopts.MinimumGoMinorVersion, so the output builds with
// every supported Go.
const goVersion = "go1.26"

// exclude lists the upstream functions that TinyGo implements by hand.
var exclude = []string{}

func main() {
	out := flag.String("out", "strconv_generated.go", "output file")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-strconv:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	env, err := exec.Command("go", "env", "GOROOT", "GOVERSION").Output()
	if err != nil {
		return err
	}
	goroot, goversion, _ := strings.Cut(strings.TrimSpace(string(env)), "\n")
	if goversion != goVersion && !strings.HasPrefix(goversion, goVersion+".") {
		return fmt.Errorf("needs %s, got %s", goVersion, goversion)
	}

	fset := token.NewFileSet()
	upstream, err := parseDir(fset, filepath.Join(goroot, "src", "internal", "strconv"), "")
	if err != nil {
		return err
	}
	local, err := parseDir(fset, filepath.Dir(out), filepath.Base(out))
	if err != nil {
		return err
	}

	for _, name := range exclude {
		found := false
		for _, f := range upstream {
			f.Decls = slices.DeleteFunc(f.Decls, func(d ast.Decl) bool {
				fd, ok := d.(*ast.FuncDecl)
				if ok && fd.Recv == nil && fd.Name.Name == name {
					found = true
					return true
				}
				return false
			})
		}
		if !found {
			return fmt.Errorf("excluded function %s not found in %s", name, goversion)
		}
	}

	// optimize selects the table driven fast paths. Folding it to false
	// keeps only the exact slow paths.
	var removed []span
	for _, f := range upstream {
		ast.Inspect(f, func(n ast.Node) bool {
			if b, ok := n.(*ast.BlockStmt); ok {
				b.List = foldOptimize(b.List, &removed)
			}
			return true
		})
	}
	if len(removed) == 0 {
		return fmt.Errorf("no optimize branches found in %s", goversion)
	}

	files := append(slices.Clone(upstream), local...)
	var info *types.Info
	for {
		var dead map[types.Object]bool
		info, dead, err = check(fset, files)
		if err != nil {
			return err
		}
		if len(dead) == 0 {
			break
		}
		for _, f := range upstream {
			removeDead(f, info, dead, &removed)
		}
	}

	declOf := map[types.Object]ast.Decl{}
	for _, f := range upstream {
		for _, d := range f.Decls {
			for _, id := range declIdents(d) {
				if obj := info.Defs[id]; obj != nil {
					declOf[obj] = d
				}
			}
		}
	}

	// Keep exported names and what the local files use, then everything
	// those reach.
	var work []types.Object
	for obj := range declOf {
		if obj.Exported() || obj.Name() == "init" {
			work = append(work, obj)
		}
	}
	for _, f := range local {
		work = append(work, uses(info, f)...)
	}
	kept := map[ast.Decl]bool{}
	imports := map[string]bool{}
	for len(work) > 0 {
		obj := work[len(work)-1]
		work = work[:len(work)-1]
		if pkg, ok := obj.(*types.PkgName); ok {
			imports[pkg.Imported().Path()] = true
			continue
		}
		d, ok := declOf[obj]
		if !ok || kept[d] {
			continue
		}
		kept[d] = true
		work = append(work, uses(info, d)...)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/gen-strconv from %s internal/strconv. DO NOT EDIT.\n\n", goversion)
	fmt.Fprintf(&buf, "// Copyright 2009 The Go Authors. All rights reserved.\n// Use of this source code is governed by a BSD-style\n// license that can be found in the LICENSE file.\n\n")
	fmt.Fprintf(&buf, "package strconv\n\n")
	fmt.Fprintf(&buf, "import (\n")
	for _, path := range slices.Sorted(maps.Keys(imports)) {
		fmt.Fprintf(&buf, "\t%q\n", path)
	}
	fmt.Fprintf(&buf, ")\n")

	for _, f := range upstream {
		for _, d := range f.Decls {
			if !kept[d] {
				continue
			}
			buf.WriteString("\n")
			node := &printer.CommentedNode{Node: d, Comments: commentsIn(f, d, removed)}
			if err := format.Node(&buf, fset, node); err != nil {
				return err
			}
			buf.WriteString("\n")
		}
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// parseDir parses the non-test Go files of the package in dir, skipping skip.
func parseDir(fset *token.FileSet, dir, skip string) ([]*ast.File, error) {
	pkg, err := build.ImportDir(dir, 0)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, name := range pkg.GoFiles {
		if name == skip {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	return files, nil
}

// declIdents returns the identifiers a top-level declaration defines.
func declIdents(d ast.Decl) []*ast.Ident {
	switch d := d.(type) {
	case *ast.FuncDecl:
		return []*ast.Ident{d.Name}
	case *ast.GenDecl:
		var ids []*ast.Ident
		for _, s := range d.Specs {
			switch s := s.(type) {
			case *ast.TypeSpec:
				ids = append(ids, s.Name)
			case *ast.ValueSpec:
				ids = append(ids, s.Names...)
			}
		}
		return ids
	}
	return nil
}

// uses returns the objects referred to inside n.
func uses(info *types.Info, n ast.Node) []types.Object {
	var objs []types.Object
	ast.Inspect(n, func(n ast.Node) bool {
		id, ok := n.(*ast.Ident)
		if !ok {
			return true
		}
		switch obj := info.Uses[id].(type) {
		case nil:
		case *types.Func:
			objs = append(objs, obj.Origin())
		case *types.Var:
			objs = append(objs, obj.Origin())
		default:
			objs = append(objs, obj)
		}
		return true
	})
	return objs
}

// commentsIn returns the comments of f inside d, including its doc comment,
// leaving out comments in removed code.
func commentsIn(f *ast.File, d ast.Decl, removed []span) []*ast.CommentGroup {
	start := d.Pos()
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Doc != nil {
			start = d.Doc.Pos()
		}
	case *ast.GenDecl:
		if d.Doc != nil {
			start = d.Doc.Pos()
		}
	}
	var groups []*ast.CommentGroup
	for _, c := range f.Comments {
		if c.Pos() < start || c.End() > d.End() {
			continue
		}
		if slices.ContainsFunc(removed, func(s span) bool { return c.Pos() >= s.pos && c.End() <= s.end }) {
			continue
		}
		groups = append(groups, c)
	}
	return groups
}

type span struct {
	pos, end token.Pos
}

// check type checks files. Removing code can leave unused imports, which
// the output leaves out, and unused local variables, which check returns.
func check(fset *token.FileSet, files []*ast.File) (*types.Info, map[types.Object]bool, error) {
	info := &types.Info{
		Defs: map[*ast.Ident]types.Object{},
		Uses: map[*ast.Ident]types.Object{},
	}
	var unused []token.Pos
	var firstErr error
	conf := types.Config{
		Importer: importer.Default(),
		Error: func(err error) {
			te := err.(types.Error)
			switch {
			case strings.Contains(te.Msg, "imported and not used"):
			case strings.HasPrefix(te.Msg, "declared and not used"):
				unused = append(unused, te.Pos)
			case firstErr == nil:
				firstErr = err
			}
		},
	}
	conf.Check("internal/strconv", fset, files, info)
	if firstErr != nil {
		return nil, nil, firstErr
	}
	dead := map[types.Object]bool{}
	for id, obj := range info.Defs {
		if obj != nil && slices.Contains(unused, id.Pos()) {
			dead[obj] = true
		}
	}
	return info, dead, nil
}

// removeDead drops the declarations of and assignments to the dead local
// variables in f.
func removeDead(f *ast.File, info *types.Info, dead map[types.Object]bool, removed *[]span) {
	isDead := func(e ast.Expr) bool {
		id, ok := e.(*ast.Ident)
		if !ok {
			return false
		}
		if obj := info.Defs[id]; obj != nil {
			return dead[obj]
		}
		return dead[info.Uses[id]]
	}
	filter := func(list []ast.Stmt) []ast.Stmt {
		return slices.DeleteFunc(list, func(s ast.Stmt) bool {
			var lhs, rhs []ast.Expr
			switch s := s.(type) {
			case *ast.AssignStmt:
				lhs, rhs = s.Lhs, s.Rhs
			case *ast.DeclStmt:
				g := s.Decl.(*ast.GenDecl)
				if g.Tok != token.VAR || len(g.Specs) != 1 {
					return false
				}
				vs := g.Specs[0].(*ast.ValueSpec)
				for _, n := range vs.Names {
					lhs = append(lhs, n)
				}
				rhs = vs.Values
			default:
				return false
			}
			if !slices.ContainsFunc(lhs, func(e ast.Expr) bool { return !isDead(e) }) && !hasCall(rhs) {
				*removed = append(*removed, span{s.Pos(), s.End()})
				return true
			}
			return false
		})
	}
	ast.Inspect(f, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.BlockStmt:
			n.List = filter(n.List)
		case *ast.CaseClause:
			n.Body = filter(n.Body)
		}
		return true
	})
}

func hasCall(exprs []ast.Expr) bool {
	found := false
	for _, e := range exprs {
		ast.Inspect(e, func(n ast.Node) bool {
			if _, ok := n.(*ast.CallExpr); ok {
				found = true
			}
			return !found
		})
	}
	return found
}

// foldOptimize returns list with optimize taken as false. It drops if
// optimize blocks, inlines if !optimize blocks, and drops the statements
// after an inlined return.
func foldOptimize(list []ast.Stmt, removed *[]span) []ast.Stmt {
	var out []ast.Stmt
	for i, s := range list {
		ifs, ok := s.(*ast.IfStmt)
		if !ok || ifs.Init != nil || ifs.Else != nil {
			out = append(out, s)
			continue
		}
		if isOptimize(ifs.Cond) {
			*removed = append(*removed, span{ifs.Pos(), ifs.End()})
			continue
		}
		if not, ok := ifs.Cond.(*ast.UnaryExpr); ok && not.Op == token.NOT && isOptimize(not.X) {
			out = append(out, ifs.Body.List...)
			if _, ok := ifs.Body.List[len(ifs.Body.List)-1].(*ast.ReturnStmt); ok && i+1 < len(list) {
				*removed = append(*removed, span{ifs.End(), list[len(list)-1].End()})
				return out
			}
			continue
		}
		out = append(out, s)
	}
	return out
}

func isOptimize(e ast.Expr) bool {
	id, ok := e.(*ast.Ident)
	return ok && id.Name == "optimize"
}
